"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 27: X자 패턴

크기 n을 입력받아 N×N 격자에서 두 대각선 위치에만 별(*)을 출력합니다.
나머지 위치에는 공백을 출력합니다.

힌트: 행 i, 열 j에서 i == j 또는 i + j == n - 1 이면 대각선입니다.
"""

n = int(input("크기 입력: "))
front_space = 0
# 아래에 X자 패턴을 출력하는 코드를 작성하세요
# 위쪽 절반
for i in range(n // 2 + 1, -1, -2):
    
    # 출력
    print((front_space * " ") + "*" + (" " * i) + "*")
    # 앞 공백
    front_space += 1
    
# 중간 별 출력
print((n // 2) * " " + "*")


# 아래쪽 절반
for i in range(1, n // 2 + 2, 2):
    # 앞 공백
    front_space -= 1
    # 출력
    print((front_space * " ") + "*" + (" " * i) + "*")

# ----------------------------------------------------
# 위쪽 절반
for i in range(n // 2):
    print(" " * i + "*" + " " * (n - 2 * i - 2) + "*")

# 가운데
print(" " * (n // 2) + "*")

# 아래쪽 절반
for i in range(n // 2 - 1, -1, -1):
    print(" " * i + "*" + " " * (n - 2 * i - 2) + "*")

