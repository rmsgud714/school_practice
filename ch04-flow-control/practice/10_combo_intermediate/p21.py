"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 21: 모래시계 패턴

높이 n(홀수)을 입력받아 모래시계 모양을 별(*)로 출력합니다.
위쪽 역삼각형과 아래쪽 삼각형을 조합합니다.

힌트: 위쪽 절반은 별이 줄어들고, 아래쪽 절반은 별이 늘어납니다.
      각 줄의 공백과 별 개수를 행 번호로 계산하세요.
"""

n = int(input("높이(홀수) 입력: "))
spcae = 1
# 아래에 모래시계 패턴을 출력하는 코드를 작성하세요

# 줄어드는 반복문
for num in range(n, 1, -2):
      # 별 출력
      print(num * "*")
      # 띄어쓰기 출력
      print(spcae * " ", end="")
      spcae += 1
      
spcae -= 1

# 늘어가는 반복문
for num in range(1, n+1, 2):
      # 별 출력
      print(num * "*")
      # 띄어쓰기 출력
      spcae -= 1
      print(spcae * " ", end="")
      

