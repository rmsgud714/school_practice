"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 30: 숫자 테두리 사각형

크기 n을 입력받아 N×N 사각형을 출력합니다.
테두리에는 바깥쪽부터 안쪽으로 1, 2, 3, ... 숫자를 채우고,
안쪽은 0으로 채웁니다.

힌트: 각 위치 (i, j)에서 가장 가까운 테두리까지의 거리를 구하면
      해당 위치의 숫자를 알 수 있습니다.
"""

n = int(input("크기 입력: "))

# 아래에 숫자 테두리 사각형을 출력하는 코드를 작성하세요
# 행 반복
for i in range(n):
    # 열 반복
    for j in range(n):

        # 가장 가까운 테두리까지의 거리 구하기
        num = min(i, j, n - 1 - i, n - 1 - j)

        # 테두리 번호 출력
        print(num + 1, end=" ")

    # 줄바꿈
    print()

