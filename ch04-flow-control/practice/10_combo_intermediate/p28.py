"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 28: 체스판 패턴

크기 n을 입력받아 N×N 체스판을 출력합니다.
#과 .을 번갈아 출력합니다.

힌트: 행과 열의 합이 짝수이면 #, 홀수이면 .을 출력합니다.
"""

n = int(input("크기 입력: "))

# 아래에 체스판 패턴을 출력하는 코드를 작성하세요
# 반복
for i in range(n):
    # 반복
    for j in range(n):
        # 행과 열의 합이 짝수이면 #
        if (i + j) % 2 == 0:
            print("#", end=" ")
        # 홀수이면 .
        else:
            print(".", end=" ")
    print()

