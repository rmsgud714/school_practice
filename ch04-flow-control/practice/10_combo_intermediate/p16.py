"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 16: 자릿수가 같은 수 (Repdigit)

1부터 N 사이에서 모든 자릿수가 동일한 수를 출력합니다.
예: 1~9, 11, 22, 33, ..., 99, 111, 222, ..., 999, ...

힌트: 각 수의 모든 자릿수가 첫째 자릿수와 같은지 확인합니다.
"""

N = int(input("N을 입력하세요: "))

# 아래에 1~N 사이에서 모든 자릿수가 동일한 수를 출력하세요
for num in range(1, N + 1):
    # num을 문자열로 변환
    num_str = str(num)

    # set으로 1자릿수 확인
    if len(set(num_str)) == 1:
        print(num)

