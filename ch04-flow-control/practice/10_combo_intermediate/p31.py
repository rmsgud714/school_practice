"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 31: ATM 시스템

잔액을 관리하는 간단한 ATM 시스템을 구현합니다.
- 초기 잔액: 100,000원
- 메뉴: 1.입금 / 2.출금 / 3.잔액조회 / 4.종료
- 출금 시 1회 출금 한도: 500,000원
- 잔액 부족 시 출금 불가
- 입금/출금 금액은 양수만 허용

힌트:
- while True로 반복하고, 메뉴 번호에 따라 if/elif로 분기합니다.
- 잔액 변수 하나로 입금(+)과 출금(-)을 관리합니다.
- 출금 시 한도 초과와 잔액 부족을 각각 체크합니다.
"""

balance = 100000

# 아래에 ATM 시스템 코드를 작성하세요

balance = 100000

# ATM 메뉴 반복
while True:
    print("===== ATM =====")
    print("1. 입금")
    print("2. 출금")
    print("3. 잔액조회")
    print("4. 종료")

    # 메뉴 선택
    menu = int(input("메뉴 선택: "))

    # 입금
    if menu == 1:
        amount = int(input("입금액: "))
        # 0 초과인 경우
        if amount > 0:
            balance += amount
            print(f"{amount}원이 입금되었습니다.")
            print(f"현재 잔액: {balance}원")
        else:
            print("입금액은 양수만 입력할 수 있습니다.")

    # 출금
    elif menu == 2:
        amount = int(input("출금액: "))

        if amount <= 0:
            print("출금액은 양수만 입력할 수 있습니다.")
        elif amount > 500000:
            print("1회 출금 한도(500000원)를 초과했습니다.")
        elif amount > balance:
            print(f"잔액이 부족합니다. 현재 잔액: {balance}원")
        else:
            balance -= amount
            print(f"{amount}원이 출금되었습니다.")
            print(f"현재 잔액: {balance}원")

    # 잔액 조회
    elif menu == 3:
        print(f"현재 잔액: {balance}원")

    # 종료
    elif menu == 4:
        print("이용해 주셔서 감사합니다.")
        break

    # 잘못된 메뉴
    else:
        print("잘못된 메뉴입니다.")
        
