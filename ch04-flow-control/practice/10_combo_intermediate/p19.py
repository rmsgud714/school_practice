"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 19: 교대 수열의 합

1 - 1/2 + 1/3 - 1/4 + 1/5 - ... 형태의 교대급수를 N항까지 계산합니다.
이 급수는 ln(2)에 수렴합니다.

힌트: 홀수 번째 항은 더하고, 짝수 번째 항은 빼면 됩니다.
"""

N = int(input("항의 수를 입력하세요: "))

# 아래에 교대 수열의 N항까지의 합을 구하세요
# 변수 초기화
total_sum = 0.0

# 반복
for index, num in enumerate(range(1, N + 1), start=1):
    # 홀수 번째 항
    if index % 2 == 1:
        total_sum += 1 / num
    else:  # 짝수 번째 항
        total_sum -= 1 / num
    # 결과 출력
    print(f"{index}항까지의 합: {total_sum:.4f}")

