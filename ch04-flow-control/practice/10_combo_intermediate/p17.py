"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 17: 증가수 찾기

1부터 N 사이에서 각 자릿수가 왼쪽에서 오른쪽으로 순증가하는 수를 출력합니다.
(한 자리 수 제외, 두 자리 이상만 출력)
예: 12, 13, 14, ..., 19, 23, 24, ..., 89, 123, 124, ...

힌트: 오른쪽부터 자릿수를 비교하여 항상 증가하는지 확인합니다.
"""

N = int(input("N을 입력하세요: "))

# 아래에 1~N 사이의 증가수를 출력하세요 (두 자리 이상)

# 반복문
for num in range(10, N + 1):
    # num을 문자열로 변환
    num_str = str(num)
    
    # 이중 반복
    for i in range(len(num_str) - 1):
        # 현재 자릿수와 다음 자릿수를 비교
        if num_str[i] >= num_str[i + 1]:
            break
    # 출력
    else:
        print(num)

