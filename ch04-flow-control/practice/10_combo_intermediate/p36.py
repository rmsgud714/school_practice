"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 36: 타이머 (카운트다운)

분:초 형태로 카운트다운하는 타이머를 구현합니다.
- 타이머 시간을 분 단위로 입력받습니다 (예: 2 → 2분 00초부터 시작)
- 1초씩 감소하며 "M분 SS초" 형태로 출력
- 초가 0이 되면 분을 1 감소시키고 초를 59로 설정
- 0분 0초가 되면 "타이머 종료!" 출력

힌트:
- 분(minutes)과 초(seconds) 변수 두 개로 관리합니다.
- while 반복문에서 초를 1씩 감소합니다.
- 초가 음수가 되면 분을 줄이고 초를 59로 되돌립니다.
- (실제로는 time.sleep(1)을 쓰지만, 여기서는 출력만 합니다.)

주의: 출력량이 많으므로 입력은 3분 이하로 테스트하세요.
"""

minutes = int(input("타이머 시간(분): "))

# 아래에 카운트다운 타이머 코드를 작성하세요

# 초
seconds = 0

# 분, 초 0이상인 경우 반복
while minutes > 0 or seconds > 0:

    # 현재 분, 초 출력
    print(f"{minutes}분 {seconds:02}초")

    # 초 감소
    seconds -= 1

    # 초가 0보다 작아지면 분 감소
    if seconds < 0:
        minutes -= 1
        seconds = 59

# 마지막 0분 0초 출력
print(f"{minutes}분 {seconds:02}초")
print("타이머 종료!")



