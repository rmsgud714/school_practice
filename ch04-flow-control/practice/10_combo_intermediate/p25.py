"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 25: 빈 다이아몬드

높이 n(홀수)을 입력받아 테두리만 별(*)이고 안쪽은 공백인
다이아몬드를 출력합니다.

힌트: 각 줄에서 첫 번째 별과 마지막 별만 출력하고 사이는 공백으로 채웁니다.
      꼭짓점(별이 1개인 줄)은 별을 하나만 출력합니다.
"""

n = int(input("높이(홀수) 입력: "))

# 아래에 빈 다이아몬드를 출력하는 코드를 작성하세요
# 위쪽 절반 출력
for i in range(n // 2 + 1):
    # 이중 for문 왼쪽 공백 출력
    for j in range(n // 2 - i):
        print(" ", end="")

    # 맨 처음 반복할 때 별 하나 출력
    if i == 0:
        print("*")
    else:
        print("*", end="")

        # 별 사이 공백
        for j in range(2 * i - 1):
            print(" ", end="")

        print("*")

# 아래쪽 절반 출력
for i in range(n // 2 - 1, -1, -1):
    # 왼쪽 공백
    for j in range(n // 2 - i):
        print(" ", end="")

    # 꼭짓점이면 별 하나 출력
    if i == 0:
        print("*")
    else:
        print("*", end="")

        # 별 사이 공백 출력
        for j in range(2 * i - 1):
            print(" ", end="")

        print("*")

